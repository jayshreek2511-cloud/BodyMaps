def _ai_component_facts(message, metrics, available_organs):
    """Answer a parent-structure question from its segmented components.

    Several structures exist only as parts: the pancreas as head/body/tail, the
    kidneys as left/right. Asked for "the volume of the pancreas", the resolver
    used to return whichever part came first in the catalog. This reports every
    part and their total instead.
    """
    norm = _ai_norm(message)
    lookup = _ai_metric_lookup(metrics, available_organs)

    families = {
        "pancreas": ("pancreas head", "pancreas body", "pancreas tail"),
        "kidney": ("kidney left", "kidney right"),
        "lung": ("lung left", "lung right"),
        "adrenal gland": ("adrenal gland left", "adrenal gland right"),
        "femur": ("femur left", "femur right"),
    }

    facts = []

    for parent, parts in families.items():
        if parent not in norm:
            continue
        if any(_ai_norm(part) in norm for part in parts):
            continue  # asked about a specific part
        whole = lookup.get(_ai_norm(parent))
        if whole and _ai_metric_valid(whole.get("volume_cm3")):
            continue  # segmented in its own right; nothing to add

        present = []
        for part in parts:
            entry = lookup.get(_ai_norm(part))
            if entry and _ai_metric_valid(entry.get("volume_cm3")):
                present.append((_ai_display(part), float(entry["volume_cm3"])))
        if not present:
            continue

        listing = ", ".join(f"{name} {volume:.2f} cm³" for name, volume in present)
        total = sum(volume for _name, volume in present)
        facts.append(
            f"SEGMENTATION FACT: the {parent} is not segmented as one structure "
            f"in this case; it is segmented in parts — {listing}. Their combined "
            f"volume is **{total:.2f} cm³**."
        )

    return facts


def _ai_case_inventory(case_id, metrics):
    """Everything measured about this case, as one compact reference block.

    This is the difference between an assistant that answers the questions
    someone enumerated and one that answers questions about the case. Rather
    than detecting "is this a volume question / a slice question / a count
    question", the model is handed the full measured picture — every structure,
    its volume, where it sits, its attenuation, and the state of every lesion
    class — and answers from it.

    Returns "" when nothing could be measured, which the caller must report
    honestly rather than papering over.
    """
    mask_path = _ai_mask_path_for(case_id)
    analysis = lesion_grounding.analyze_structures(mask_path, cache_key=str(case_id))

    # Attenuation only exists in the computed metrics, so index them by name to
    # merge onto the labelmap-derived geometry.
    hu_by_key = {}
    for entry in metrics or []:
        organ = _ai_norm(entry.get("organ_name"))
        value = entry.get("mean_hu")
        if organ and (_ai_metric_valid(value) or value == 0):
            hu_by_key[organ] = float(value)

    lines = []

    if analysis.get("available") and analysis.get("structures"):
        structures = analysis["structures"]
        lesion_ids = set(lesion_grounding.LESION_LABELS)
        for label_id, entry in sorted(structures.items()):
            meta = MESH_LABELS.get(label_id) if MESH_LABELS else None
            if not meta or label_id in lesion_ids:
                continue
            bits = [f"{meta['name']}: {entry['volume_cm3']:.2f} cm³"]
            rng = entry.get("slice_range")
            if rng:
                bits.append(f"axial slices {rng[0]}-{rng[1]}")
            hu = hu_by_key.get(_ai_norm(meta["key"]))
            if hu is not None:
                bits.append(f"mean {hu:.1f} HU")
            lines.append("- " + ", ".join(bits))
    else:
        # No readable labelmap — fall back to whatever metrics exist.
        for entry in metrics or []:
            name = entry.get("display_name") or _ai_display(entry.get("organ_name"))
            volume = entry.get("volume_cm3")
            if not _ai_metric_valid(volume):
                continue
            bits = [f"{name}: {float(volume):.2f} cm³"]
            hu = entry.get("mean_hu")
            if _ai_metric_valid(hu) or hu == 0:
                bits.append(f"mean {float(hu):.1f} HU")
            lines.append("- " + ", ".join(bits))

    if not lines:
        return ""

    header = (
        f"CASE INVENTORY — every structure measured from this case's own "
        f"segmentation ({len(lines)} structures). These values are exact; quote "
        "them verbatim and never recompute or estimate them."
    )

    block = [header] + lines

    # Lesion classes are stated explicitly, present or absent, so "is there a
    # tumour anywhere?" has an answer without a separate lookup.
    lesion_analysis = lesion_grounding.analyze_lesions(mask_path, cache_key=str(case_id))
    if lesion_analysis.get("available"):
        states = []
        for entry in lesion_analysis.get("lesions", []):
            if not entry.get("present"):
                states.append(f"{entry['display']}: none")
            elif entry.get("diffuse"):
                states.append(
                    f"{entry['display']}: {entry['volume_cm3']:.2f} cm³ but "
                    "scattered, not one discrete lesion"
                )
            else:
                where = f" in the pancreatic {entry['region']}" if entry.get("region") else ""
                states.append(
                    f"{entry['display']}: present{where}, "
                    f"{entry['volume_cm3']:.2f} cm³, centred on axial slice "
                    f"{entry.get('axial_slice')}"
                )
        if states:
            block.append("Lesion classes — " + "; ".join(states) + ".")

    return "\n".join(block)


def _ai_structure_facts(case_id, message):
    """Exact inventory and slice-level answers, straight from the labelmap.

    Covers the two questions that previously returned nothing: what the
    segmentation contains, and where a named structure sits along the scan.
    """
    wants_inventory = ai_reasoning.asks_for_inventory(message)
    wants_slice = ai_reasoning.asks_for_slice_level(message)
    if not (wants_inventory or wants_slice):
        return []

    analysis = lesion_grounding.analyze_structures(
        _ai_mask_path_for(case_id), cache_key=str(case_id)
    )
    if not analysis.get("available"):
        return []

    structures = analysis.get("structures") or {}
    if not structures:
        return []

    named = []
    for label_id, entry in sorted(structures.items()):
        meta = MESH_LABELS.get(label_id) if MESH_LABELS else None
        if not meta:
            continue
        named.append((meta["name"], meta["key"], entry))

    facts = []

    if wants_inventory and named:
        listing = ", ".join(
            f"{name} {entry['volume_cm3']:.2f} cm³" for name, _key, entry in named
        )
        facts.append(
            f"SEGMENTATION FACT: this case has **{len(named)} segmented "
            f"structures**, with these measured volumes — {listing}."
        )

    if wants_slice:
        norm = _ai_norm(message)
        # Longest key first so "pancreas head" wins over "pancreas".
        lesion_keys = {meta["key"] for meta in lesion_grounding.LESION_LABELS.values()}
        for name, key, entry in sorted(named, key=lambda item: -len(item[1])):
            # Lesions are answered by the lesion path, which checks whether the
            # class is a discrete finding at all. Quoting a slice range here
            # would state a precise location for scattered false positives.
            if key in lesion_keys:
                continue
            if _ai_norm(key) not in norm and _ai_norm(name) not in norm:
                continue
            rng = entry.get("slice_range")
            if not rng:
                continue
            facts.append(
                f"SEGMENTATION FACT: the {name} spans axial slices "
                f"**{rng[0]}–{rng[1]}**, centred on slice "
                f"**{entry.get('centre_slice', rng[0])}**, and measures "
                f"**{entry['volume_cm3']:.2f} cm³**."
            )
            break

    return facts


def _ai_lesion_context(case_id, message):
    """Measured lesion findings for this case, ready to put in the prompt.

    Returns the authoritative fact sentences plus which lesion classes are
    present and absent, so the answer can be checked against them afterwards.
    When the labelmap cannot be read this reports `available: False` and the
    assistant must say the segmentation was not checked — never guess.
    """
    focus = ai_reasoning.lesion_focus_organs(message)
    mask_path = _ai_mask_path_for(case_id)
    analysis = lesion_grounding.analyze_lesions(mask_path, cache_key=str(case_id))

    absent, present = [], []
    if analysis.get("available"):
        wanted = set(focus)
        for entry in analysis.get("lesions", []):
            if wanted and entry.get("organ") not in wanted:
                continue
            # A scattered class is neither a clean finding nor a clean absence,
            # so it takes part in no contradiction check: saying "no single
            # lesion location" about it is correct, not a denial to overturn.
            if entry.get("diffuse"):
                continue
            (present if entry.get("present") else absent).append(entry["display"])

    facts = lesion_grounding.lesion_facts(analysis, focus)
    if not analysis.get("available"):
        reason = str(analysis.get("reason") or "the segmentation is unavailable")
        facts = [
            "SEGMENTATION FACT: the lesion classes could not be checked for this "
            f"case ({reason}). Say the segmentation could not be verified and do "
            "not state whether a lesion exists."
        ]

    return {
        "facts": facts,
        "absent": absent,
        "present": present,
        "available": bool(analysis.get("available")),
        # Same information as prose, used when no model is reachable so a lesion
        # question still gets a correct answer instead of an outage message.
        "summary": lesion_grounding.lesion_summary(analysis, focus),
    }


def _ai_load_metrics(case_id, supplied_metrics):
    """
    Prefer server-computed segmentation metrics.

    If the server does not have local NIfTI data, use metrics supplied by
    the frontend. Never allow a missing local file to prevent Ollama from
    answering general educational questions.
    """

    identifier = str(case_id or "").strip()

    if identifier and identifier in _AI_METRICS_CACHE:
        return _AI_METRICS_CACHE[identifier]

    # Fast path: the browser already fetched these from THIS server's
    # /api/mask-data, so they are the same numbers the block below would
    # recompute — identical accuracy, minus a possible NIfTI download and a
    # full voxel pass that can stall the first question about a case.
    if isinstance(supplied_metrics, list) and supplied_metrics:
        cleaned = [
            _ai_public_metric(item)
            for item in supplied_metrics
            if isinstance(item, dict)
        ]
        if cleaned:
            if identifier:
                _AI_METRICS_CACHE[identifier] = (cleaned, "frontend_supplied_metrics")
            return cleaned, "frontend_supplied_metrics"

    if identifier and _is_safe_id(identifier):
        try:
            if identifier.isdigit():
                result = get_mask_data_internal(identifier)
                # Fall back to the robust label-based computation (with HF
                # download) when the local dataset path is unavailable, so
                # organ-volume questions still resolve to real numbers.
                if not isinstance(result, dict) or result.get("error") or not result.get("organ_metrics"):
                    robust = _ai_compute_organ_metrics_from_labels(identifier)
                    if robust and robust.get("organ_metrics"):
                        result = robust
                source = "server_mask_data"
            else:
                # Optional session metric helper isn't shipped in every deployment.
                # Import lazily so its absence doesn't prevent the entire Flask app
                # (including Live Rooms) from starting; this branch already falls
                # back to frontend-supplied metrics on any error below.
                from services.segmentation_metrics import calculate_session_metrics
                result = calculate_session_metrics(
                    identifier,
                    Constants.SESSIONS_DIR_NAME,
                )
                if not isinstance(result, dict) or result.get("error") or not result.get("organ_metrics"):
                    robust = _ai_compute_organ_metrics_from_labels(identifier)
                    if robust and robust.get("organ_metrics"):
                        result = robust
                source = "session_mask_data"

            if isinstance(result, dict) and not result.get("error"):
                raw_metrics = result.get("organ_metrics") or []

                if isinstance(raw_metrics, list):
                    cleaned = [
                        _ai_public_metric(item)
                        for item in raw_metrics
                        if isinstance(item, dict)
                    ]

                    if cleaned:
                        _AI_METRICS_CACHE[identifier] = (cleaned, source)
                        return cleaned, source

        except Exception as error:
            # Missing local case data should not disable general AI chat.
            print(
                "[AI metrics unavailable]",
                type(error).__name__,
                str(error),
            )

    if isinstance(supplied_metrics, list):
        cleaned = [
            _ai_public_metric(item)
            for item in supplied_metrics
            if isinstance(item, dict)
        ]

        if cleaned:
            return cleaned, "frontend_supplied_metrics"

    return [], "unavailable"


def _ai_metric_lookup(metrics, available_organs):
    lookup = {}
    for entry in metrics:
        organ_name = entry.get("organ_name")
        display_name = entry.get("display_name") or _ai_display(organ_name)
        for key in {organ_name, display_name, _ai_norm(organ_name), _ai_norm(display_name)}:
            if key:
                lookup[_ai_norm(key)] = entry
    for organ in available_organs:
        key = _ai_norm(organ)
        if key not in lookup:
            # Keep the viewer catalog entry available for honest “metric unavailable” responses.
            lookup[key] = {"organ_name": organ, "display_name": _ai_display(organ), "volume_cm3": None, "mean_hu": None}
    return lookup


def _ai_legend_answer(message, mask_legend):
    """Deterministic answer to a 'which color is the <organ>?' question, built
    straight from the mask color legend. Lets us answer color-identification
    questions instantly and reliably without waiting on the vision model."""
    if not mask_legend:
        return None
    norm = _ai_norm(message)

    def _pretty(organ):
        return str(organ).replace("_", " ")

    matched = []
    for entry in mask_legend:
        organ = str(entry.get("organ") or "")
        words = [w for w in _ai_norm(organ).split() if len(w) > 2]
        if _ai_norm(organ) in norm or any(w in norm for w in words):
            matched.append(entry)

    picks = matched or mask_legend[:8]
    parts = [
        f"the {_pretty(e.get('organ'))} is shown in {e.get('color')}"
        for e in picks
        if e.get("organ") and e.get("color")
    ]
    if not parts:
        return None
    return "In the segmentation overlay, " + "; ".join(parts) + "."


def _ai_strip_think(text, orphan_closer=False):
    """Remove model reasoning that leaks into the answer text.

    Always handles:
      - complete <think>...</think> blocks (possibly several),
      - an unclosed trailing <think> (block still streaming).

    With orphan_closer=True (pass ONLY for reasoning-family models) it also
    treats everything before a bare closing </think> as reasoning — the shape
    qwen3 leaks on some Ollama versions. Non-reasoning models keep a literal
    </think> in their prose untouched (e.g. when the user asks about the tag),
    which also keeps streamed deltas monotonic for them.
    """
    if not text:
        return ""
    out = text
    while "<think>" in out:
        start = out.find("<think>")
        end = out.find("</think>", start)
        if end == -1:  # unclosed block still streaming — drop the tail
            out = out[:start]
            break
        out = out[:start] + out[end + len("</think>"):]
    if orphan_closer and "</think>" in out:
        out = out.rsplit("</think>", 1)[1]
    return out.lstrip("\n")


# Models whose output can carry a chain-of-thought. The stream endpoint holds
# their text back until the reasoning is provably over (or the stream ends), so
# thinking is never shown even when it leaks without an opening <think> tag.
# qwen3-vl (instruct) is excluded — it does not reason and should stream live —
# but any "*-thinking" variant is included.
_AI_REASONING_MODEL_RE = re.compile(
    r"qwen3(?!-vl)|deepseek-r1|-r1\b|qwq|marco-o1|thinking", re.IGNORECASE
)


