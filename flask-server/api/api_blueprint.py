def _ai_agent_execute(name, args, *, metrics, metadata, available_organs, references):
    """Execute one agent tool server-side.

    Returns (status_text, result_text, viewer_actions, is_data_fact).
    result_text goes back to the model as the tool result; data facts are also
    carried into the final answer's Facts so the safety net can verify them.
    """
    args = args if isinstance(args, dict) else {}

    if name == "get_organ_metric":
        organ_raw = str(args.get("organ") or "").strip()
        resolved = _ai_resolve_organ(organ_raw, available_organs) or organ_raw
        entry = _ai_metric_lookup(metrics, available_organs).get(_ai_norm(resolved))
        display = _ai_display(resolved or organ_raw)
        if not entry:
            names = ", ".join(available_organs[:40]) or "none"
            return (
                f"Measuring the {display.lower()}",
                f"No measurement for '{organ_raw}' in this case. Available structures: {names}.",
                [],
                False,
            )
        parts = []
        volume = entry.get("volume_cm3")
        mean_hu = entry.get("mean_hu")
        if _ai_metric_valid(volume):
            parts.append(f"The segmented {display} volume is **{float(volume):.2f} cm³**.")
        if _ai_metric_valid(mean_hu) or mean_hu == 0:
            parts.append(f"The segmented {display} mean attenuation is **{float(mean_hu):.1f} HU**.")
        for ref in references or []:
            if _ai_norm(ref.get("organ_name")) == _ai_norm(resolved):
                pct = ref.get("percentile")
                if isinstance(pct, (int, float)):
                    basis = str(ref.get("basis") or "").strip()
                    suffix = f" ({basis})" if basis else ""
                    parts.append(
                        f"That volume is at the **{float(pct):.0f}th percentile** of the reference cohort{suffix}."
                    )
                break
        result = " ".join(parts) if parts else f"No valid measurements recorded for {display}."
        return (f"Measuring the {display.lower()}", result, [], bool(parts))

    if name == "list_structures":
        names = ", ".join(available_organs) or "none"
        return (
            "Listing segmented structures",
            f"This case has {len(available_organs)} segmented structures: {names}.",
            [],
            False,
        )

    if name == "get_patient_info":
        if not metadata:
            return (
                "Checking patient information",
                "No patient metadata (age, sex, BMI...) is available for this case.",
                [],
                False,
            )
        fields = ", ".join(f"{key}: {value}" for key, value in metadata.items())
        return ("Checking patient information", f"Patient metadata — {fields}.", [], True)

    if name == "show_in_viewer":
        organs = args.get("organs")
        organs = [str(o).strip() for o in organs if str(o).strip()] if isinstance(organs, list) else []
        actions = _ai_sanitize_actions([{"type": "isolate_organs", "organs": organs}], available_organs)
        if not actions:
            return (
                "Updating the viewer",
                f"Could not match {organs or 'those organs'} to this case's structures.",
                [],
                False,
            )
        shown = ", ".join(_ai_display(o) for o in actions[0].get("organs", []))
        return ("Updating the viewer", f"Done — isolated {shown} in the viewer.", actions, False)

    if name == "set_window_preset":
        preset = str(args.get("preset") or "").strip()
        if preset not in {"soft_tissue", "bone", "lung", "liver"}:
            return ("Adjusting the window", f"Unknown preset '{preset}'.", [], False)
        actions = [{"type": "set_window_preset", "preset": preset}]
        return (
            "Adjusting the window",
            f"Done — applied the {preset.replace('_', ' ')} window preset.",
            actions,
            False,
        )

    return ("", f"Unknown tool '{name}'.", [], False)


def _ai_required_metric_facts(actions, metrics, available_organs):
    """Exact measurement sentence(s) the reply MUST contain — one per
    get_organ_metric action — so a request like "segment the liver and give
    me its volume" always includes the real, dataset-derived number.
    """
    lookup = _ai_metric_lookup(metrics, available_organs)
    facts = []
    for action in actions or []:
        if action.get("type") != "get_organ_metric":
            continue
        entry = lookup.get(_ai_norm(action.get("organ")))
        if not entry:
            continue
        organ = _ai_display(action.get("organ"))
        metric = action.get("metric") or "volume_cm3"
        volume = entry.get("volume_cm3")
        mean_hu = entry.get("mean_hu")
        if metric in ("volume_cm3", "all") and _ai_metric_valid(volume):
            facts.append(f"The segmented {organ} volume is **{float(volume):.2f} cm³**.")
        if metric in ("mean_hu", "all") and (_ai_metric_valid(mean_hu) or mean_hu == 0):
            facts.append(f"The segmented {organ} mean attenuation is **{float(mean_hu):.1f} HU**.")
    return facts


def _ai_resolve_organ(value, available_organs):
    norm = _ai_norm(value)
    if not norm:
        return None

    normalized_available = [(organ, _ai_norm(organ)) for organ in available_organs]
    for organ, organ_norm in normalized_available:
        if norm == organ_norm:
            return organ
    # Partial matches are RANKED, not first-come. Returning the first organ whose
    # name merely contains the query answered "what is the volume of the
    # pancreas?" with the pancreas TAIL, because the tail came first in the
    # catalog — a real measurement of the wrong structure.
    lesion_norms = {
        _ai_norm(meta["key"]) for meta in lesion_grounding.LESION_LABELS.values()
    }
    query_words = set(norm.split())
    ranked = []
    for organ, organ_norm in normalized_available:
        if norm not in organ_norm and organ_norm not in norm:
            continue
        # A plain organ query must never land on a lesion class.
        if organ_norm in lesion_norms:
            continue
        # Nor on a COMPONENT of itself: "pancreas" is not "pancreas body".
        # _ai_component_facts answers those with every part plus a total.
        if query_words < set(organ_norm.split()):
            continue
        ranked.append((organ, organ_norm))
    if ranked:
        # Shortest name = fewest added qualifiers = closest to what was asked.
        ranked.sort(key=lambda item: (len(item[1]), item[1]))
        return ranked[0][0]

    alias_groups = [
        {"left kidney", "kidney left", "left renal", "left renal kidney"},
        {"right kidney", "kidney right", "right renal", "right renal kidney"},
        {"gall bladder", "gallbladder"},
        {"inferior vena cava", "ivc", "vena cava", "postcava"},
        {"superior mesenteric artery", "sma"},
        {"common bile duct", "bile duct", "cbd"},
        {"left adrenal", "left adrenal gland", "adrenal gland left"},
        {"right adrenal", "right adrenal gland", "adrenal gland right"},
    ]
    for aliases in alias_groups:
        normalized_aliases = {_ai_norm(alias) for alias in aliases}
        if norm not in normalized_aliases:
            continue
        for organ, organ_norm in normalized_available:
            if organ_norm in normalized_aliases:
                return organ
    return None


def _ai_sanitize_actions(actions, available_organs):
    if not isinstance(actions, list):
        return []
    sanitized = []
    seen = set()
    for action in actions[:8]:
        if not isinstance(action, dict):
            continue
        action_type = action.get("type")
        if action_type not in AI_ALLOWED_ACTION_TYPES:
            continue
        clean = {"type": action_type}
        if action_type in {"isolate_organs", "show_organs", "hide_organs"}:
            organs = action.get("organs")
            if not isinstance(organs, list):
                continue
            resolved = []
            for organ in organs:
                found = _ai_resolve_organ(organ, available_organs)
                if found and found not in resolved:
                    resolved.append(found)
            if not resolved:
                continue
            clean["organs"] = resolved
        elif action_type == "focus_organ":
            found = _ai_resolve_organ(action.get("organ"), available_organs)
            if not found:
                continue
            clean["organ"] = found
        elif action_type == "get_organ_metric":
            found = _ai_resolve_organ(action.get("organ"), available_organs)
            if not found:
                continue
            metric = action.get("metric") or "volume_cm3"
            if metric not in AI_ALLOWED_METRICS:
                metric = "volume_cm3"
            clean["organ"] = found
            clean["metric"] = metric
        elif action_type == "set_opacity":
            try:
                clean["value"] = max(0, min(100, float(action.get("value"))))
            except (TypeError, ValueError):
                continue
        elif action_type == "set_window":
            try:
                clean["width"] = max(1, float(action.get("width")))
                clean["center"] = float(action.get("center"))
            except (TypeError, ValueError):
                continue
        elif action_type == "set_window_preset":
            preset = action.get("preset")
            if preset not in AI_ALLOWED_PRESETS:
                continue
            clean["preset"] = preset
        elif action_type == "set_zoom":
            try:
                clean["value"] = max(0.1, min(20, float(action.get("value"))))
            except (TypeError, ValueError):
                continue
        elif action_type == "set_view":
            view = action.get("view")
            if view not in AI_ALLOWED_VIEWS:
                continue
            clean["view"] = view
        elif action_type == "activate_measurement_tool":
            tool = action.get("tool")
            if tool not in AI_ALLOWED_TOOLS:
                continue
            clean["tool"] = tool

        key = json.dumps(clean, sort_keys=True)
        if key not in seen:
            sanitized.append(clean)
            seen.add(key)
    return sanitized


def _ai_action_family(action_type):
    if action_type in {"isolate_organs", "show_organs", "hide_organs", "focus_organ"}:
        return "organ_visibility"
    if action_type in {"set_window", "set_window_preset"}:
        return "window"
    if action_type in {"set_zoom", "zoom_to_fit"}:
        return "zoom"
    if action_type in {"activate_measurement_tool", "clear_measurements"}:
        return "measurement_tool"
    if action_type in {"list_structures", "get_structure_count", "get_largest_structure", "get_smallest_structure"}:
        return "structure_query"
    return action_type


def _ai_merge_actions(deterministic_actions, model_actions):
    """Prefer deterministic actions for recognized commands and let Ollama fill gaps."""
    merged = []
    seen = set()
    used_families = set()
    for action in [*(deterministic_actions or []), *(model_actions or [])]:
        if not isinstance(action, dict):
            continue
        key = json.dumps(action, sort_keys=True)
        if key in seen:
            continue
        family = _ai_action_family(action.get("type"))
        # A command should not apply conflicting visibility/window/zoom/tool actions.
        if family in used_families and family != "get_organ_metric":
            continue
        merged.append(action)
        seen.add(key)
        used_families.add(family)
    return merged[:8]


def _ai_metadata(case_id, supplied):
    metadata = {}
    if isinstance(supplied, dict):
        for key in ["sex", "age", "bmi", "height_cm", "weight_kg"]:
            if supplied.get(key) not in [None, ""]:
                metadata[key] = supplied.get(key)
    if case_id and str(case_id).isdigit():
        entry = _METADATA_CACHE.get(get_panTS_id(str(case_id)), {})
        if entry.get("age") not in [None, ""]:
            try:
                metadata["age"] = float(entry.get("age"))
            except (TypeError, ValueError):
                metadata["age"] = entry.get("age")
        if entry.get("sex") not in [None, ""]:
            metadata["sex"] = entry.get("sex")
    if "bmi" not in metadata:
        try:
            height_m = float(metadata.get("height_cm")) / 100
            weight_kg = float(metadata.get("weight_kg"))
            if height_m > 0 and weight_kg > 0:
                metadata["bmi"] = round(weight_kg / (height_m * height_m), 1)
        except (TypeError, ValueError):
            pass
    return metadata


